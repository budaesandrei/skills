"""
extract-theme.py — Generate full light+dark CSS custom properties from a logo or hex color.

Usage:
    python extract-theme.py --color "#0047AB"
    python extract-theme.py --color "#0047AB" --variant expressive
    python extract-theme.py --image path/to/logo.png
    python extract-theme.py --image path/to/logo.png --variant fidelity --output theme.css
"""

import argparse
import sys
from material_color_utilities import (
    Variant,
    hex_from_argb,
    theme_from_color,
    theme_from_image,
)
from PIL import Image

VARIANTS = {
    "tonal_spot": Variant.TONALSPOT,
    "neutral": Variant.NEUTRAL,
    "vibrant": Variant.VIBRANT,
    "expressive": Variant.EXPRESSIVE,
    "fidelity": Variant.FIDELITY,
    "content": Variant.CONTENT,
    "monochrome": Variant.MONOCHROME,
    "rainbow": Variant.RAINBOW,
    "fruit_salad": Variant.FRUITSALAD,
}

SCHEME_ROLES = [
    "primary", "on_primary", "primary_container", "on_primary_container",
    "secondary", "on_secondary", "secondary_container", "on_secondary_container",
    "tertiary", "on_tertiary", "tertiary_container", "on_tertiary_container",
    "error", "on_error", "error_container", "on_error_container",
    "surface", "on_surface", "surface_variant", "on_surface_variant",
    "surface_container_lowest", "surface_container_low", "surface_container",
    "surface_container_high", "surface_container_highest",
    "surface_dim", "surface_bright",
    "outline", "outline_variant", "shadow", "scrim",
    "inverse_surface", "inverse_on_surface", "inverse_primary",
]


def scheme_to_css_vars(scheme, prefix=""):
    """Convert a scheme object to CSS custom properties."""
    lines = []
    for role in SCHEME_ROLES:
        value = getattr(scheme, role, None)
        if value is not None:
            var_name = f"--{prefix}{role.replace('_', '-')}"
            lines.append(f"  {var_name}: {value};")
    return lines


def generate_css(theme, include_both=True):
    """Generate CSS custom properties for light and dark themes."""
    output = []
    output.append("/* Generated by extract-theme.py (Material Design 3) */")
    output.append("")

    # Light theme
    output.append(":root {")
    output.append("  color-scheme: light;")
    output.extend(scheme_to_css_vars(theme.schemes.light))
    output.append("}")
    output.append("")

    if include_both:
        # Dark theme via prefers-color-scheme
        output.append("@media (prefers-color-scheme: dark) {")
        output.append("  :root {")
        output.append("    color-scheme: dark;")
        for line in scheme_to_css_vars(theme.schemes.dark):
            output.append(f"  {line}")
        output.append("  }")
        output.append("}")
        output.append("")

        # Manual dark class override
        output.append(".dark {")
        output.append("  color-scheme: dark;")
        output.extend(scheme_to_css_vars(theme.schemes.dark))
        output.append("}")

    return "\n".join(output)


def main():
    parser = argparse.ArgumentParser(description="Generate M3 light+dark CSS theme from color or image")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--color", help="Source hex color (e.g. '#0047AB')")
    group.add_argument("--image", help="Path to logo/image to extract theme from")
    parser.add_argument("--variant", default="tonal_spot", choices=VARIANTS.keys(),
                        help="Theme variant (default: tonal_spot)")
    parser.add_argument("--contrast", type=float, default=0.0,
                        help="Contrast level -1.0 to 1.0 (default: 0.0)")
    parser.add_argument("--output", "-o", help="Output file path (default: stdout)")
    args = parser.parse_args()

    variant = VARIANTS[args.variant]

    if args.color:
        color = args.color.lstrip("#")
        if len(color) == 6:
            color = f"#{color}"
        theme = theme_from_color(color, args.contrast, variant)
        source_desc = f"color: {args.color}"
    else:
        img = Image.open(args.image)
        theme = theme_from_image(img, args.contrast, variant)
        source_desc = f"image: {args.image}"

    css = generate_css(theme)
    header = f"/* Source: {source_desc} | Variant: {args.variant} | Contrast: {args.contrast} */\n"
    result = header + css

    if args.output:
        with open(args.output, "w") as f:
            f.write(result)
        print(f"Theme written to {args.output}")
    else:
        print(result)


if __name__ == "__main__":
    main()
